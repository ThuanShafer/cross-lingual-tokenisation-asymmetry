const times = (v) => `×${v.toFixed(2)}`;
const HEADLINE_KEYS = ["promptTokens", "tokensPerWord", "waitMs", "costPerMillionWords"];

function Stat({ summary, format }) {
  return (
    <>
      {format(summary.mean)}
      {summary.n > 1 && <span className="sd"> ±{format(summary.sd)}</span>}
    </>
  );
}

function direction(row) {
  return row.higherIsWorse ? "higher is worse" : "higher is better";
}

function Abstract({ analysis }) {
  const { languages, model, overall, totalRuns } = analysis;
  const prompt = analysis.byMetric("promptTokens");
  const fertility = analysis.byMetric("tokensPerWord");
  const costPerWord = analysis.byMetric("costPerMillionWords");
  const names = languages.map((l) => l.finding.target.name);

  return (
    <section className="abstract">
      <p>
        <b>Abstract.</b> We measure the cross-lingual tokenization asymmetry of the locally hosted language model{" "}
        <i>{model.name}</i> ({model.parameterSize}) by posing the same question in English and in {languages.length}{" "}
        other language{languages.length === 1 ? "" : "s"} ({names.join(", ")}), each answered natively by the same model.
        Over {totalRuns} paired runs, the non-English queries required on average {times(prompt.mean)} the prompt tokens of
        English (highest: {prompt.highest.finding.target.name}, {times(prompt.highest.metrics.promptTokens.ratio.mean)}),
        with a tokenizer fertility of {times(fertility.mean)} tokens per word relative to English. Normalised for answer
        length, cost per word was {times(costPerWord.mean)} that of English on average. Aggregated over all twelve metrics,
        the overall penalty ranged from {times(overall.lowest.overall.mean)} ({overall.lowest.finding.target.name}) to{" "}
        {times(overall.highest.overall.mean)} ({overall.highest.finding.target.name}).
        {analysis.agreement &&
          ` Semantic agreement between each answer and the English answer (LaBSE, chance-rescaled; 1 = same meaning) averaged ${analysis.agreement.answer.toFixed(2)}, from ${analysis.agreement.highest.finding.agreement.answer.toFixed(2)} (${analysis.agreement.highest.finding.target.name}) down to ${analysis.agreement.lowest.finding.agreement.answer.toFixed(2)} (${analysis.agreement.lowest.finding.target.name}).`}{" "}
        The results quantify how languages that
        are under-represented in tokenizer training data pay more in tokens, latency, memory and money for the same request.
      </p>
      <p className="text-[8.5pt]">
        <b>Keywords:</b> tokenization, multilingual NLP, language model fairness, Te Reo Māori, inference cost
      </p>
    </section>
  );
}

