function AgreementMethod({ analysis }) {
  const a = analysis.agreement;
  if (!a) return null;
  return (
    <>
      <h3>2.6 Semantic agreement of answers</h3>
      <p>
        Cost only matters if the answers are comparable, so we also measure how closely each non-English answer matches the
        English answer in meaning. <i>Direct agreement</i> embeds both answers with the multilingual sentence encoder{" "}
        {a.encoders.crossLingual} {cite("labse2022")}, which covers all languages studied, and takes their cosine similarity.
        Because raw LaBSE similarities are compressed (unrelated sentences already score around {a.baseline.toFixed(2)}),
        scores are rescaled against that chance baseline, s′ = (s − b) / (1 − b), following the baseline rescaling used by
        BERTScore {cite("bertscore2020")}; b is the mean similarity of eight unrelated cross-lingual sentence pairs. As a
        cross-check that does not depend on the multilingual encoder, <i>back-translated agreement</i> compares the English
        answer with the NLLB back-translation of the non-English answer using the English encoder {a.encoders.english}{" "}
        {cite("sbert2019")}. Finally, <i>query fidelity</i> applies the direct measure to the two queries to verify that the
        machine translation preserved the question. All scores use the first run of each comparison; 1 means the same
        meaning and 0 means unrelated.
      </p>
    </>
  );
}

function AgreementResults({ analysis, figureNumber }) {
  const a = analysis.agreement;
  if (!a) return null;
  const rows = a.languages.flatMap((l) => [
    { label: l.finding.target.name, mean: l.finding.agreement.answer, sd: 0, tone: "target" },
    { label: "via back-transl.", mean: l.finding.agreement.answerBackTranslated, sd: 0, tone: "secondary" },
  ]);
  return (
    <>
      <h3>3.1 Semantic agreement of answers</h3>
      <p>
        Direct agreement with the English answer averaged {a.answer.toFixed(2)} across languages (back-translated:{" "}
        {a.answerBackTranslated.toFixed(2)}), with the highest agreement for {a.highest.finding.target.name} (
        {a.highest.finding.agreement.answer.toFixed(2)}) and the lowest for {a.lowest.finding.target.name} (
        {a.lowest.finding.agreement.answer.toFixed(2)}). Query fidelity averaged {a.query.toFixed(2)}
        {a.query >= 0.7
          ? ": the questions themselves were largely preserved, so low answer agreement reflects how the model answered rather than the query translation."
          : ", so part of the answer divergence may stem from the query translation itself."}{" "}
        In everyday terms the closest match was {a.highest.finding.target.name} (
        {describeScore(a.highest.finding.agreement.answer).phrase})
        {a.lowest.finding.target.code !== a.highest.finding.target.code
          ? ` and the furthest was ${a.lowest.finding.target.name} (${describeScore(a.lowest.finding.agreement.answer).phrase})`
          : ""}
        . {describeAgreement(a.lowest.finding.agreement, a.lowest.finding.target.name).headline} Figure {figureNumber}{" "}
        and Table 3 give the per-language scores.
      </p>
      <figure className="narrow">
        <BarFigure rows={rows} format={(v) => v.toFixed(2)} domainMax={1} ariaLabel="Semantic agreement with the English answer" />
        <figcaption>
          <b>Figure {figureNumber}.</b> Semantic agreement of each answer with the English answer (1 = same meaning,
          0 = unrelated). Coloured: direct, {a.encoders.crossLingual} rescaled against chance; grey: English encoder on
          the NLLB back-translation.
        </figcaption>
      </figure>
      <div className="table-wrap">
        <table>
          <caption>
            <b>Table 3.</b> Semantic agreement with English (first run). Direct and query scores are {a.encoders.crossLingual}{" "}
            similarities rescaled against a chance baseline of {a.baseline.toFixed(3)}.
          </caption>
          <thead>
            <tr>
              <th>Language</th>
              <th>Answer, direct</th>
              <th>In plain terms</th>
              <th>Answer, via back-translation</th>
              <th>Query fidelity</th>
            </tr>
          </thead>
          <tbody>
            {a.languages.map((l) => (
              <tr key={l.finding.target.code}>
                <th>{l.finding.target.name}</th>
                <td>{l.finding.agreement.answer.toFixed(2)}</td>
                <td>{describeScore(l.finding.agreement.answer).phrase}</td>
                <td>{l.finding.agreement.answerBackTranslated.toFixed(2)}</td>
                <td>{l.finding.agreement.query.toFixed(2)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </>
  );
}

function Results({ analysis }) {
  const { languages, english, overall } = analysis;
  const overallRows = languages.map((l) => ({
    label: l.finding.target.name,
    mean: l.overall.mean,
    sd: l.overall.sd,
    tone: "target",
  }));

  return (
    <>
      <h2>3. Results</h2>
      <p>
        Figure 1 summarises the overall penalty per language. {overall.highest.finding.target.name} carries the largest
        overall penalty ({times(overall.highest.overall.mean)}), {overall.lowest.finding.target.name} the smallest (
        {times(overall.lowest.overall.mean)}). In everyday terms, {overall.highest.finding.target.name} cost{" "}
        {asMuchAs(overall.highest.overall.mean)}
        {overall.lowest.finding.target.code !== overall.highest.finding.target.code
          ? `, while ${overall.lowest.finding.target.name} cost ${asMuchAs(overall.lowest.overall.mean)}`
          : ""}
        . Table 2 reports every metric for every language; Figures 2–13 break the comparison down by metric.
      </p>
      <p>
        {HEADLINE_KEYS.map((key) => {
          const row = getMetricRow(key);
          const s = analysis.byMetric(key);
          return `${row.label}: ${times(s.mean)} English on average (max ${s.highest.finding.target.name} ${times(s.highest.metrics[key].ratio.mean)}). `;
        })}
      </p>

      <figure className="narrow">
        <BarFigure rows={overallRows} format={(v) => `×${v.toFixed(2)}`} reference={1} ariaLabel="Overall penalty per language" />
        <figcaption>
          <b>Figure 1.</b> Overall penalty relative to English (geometric mean over twelve metrics, oriented so that &gt;1
          is worse); mean ± SD over runs. Dashed line: English parity (×1).
        </figcaption>
      </figure>

      <div className="table-wrap">
        <table>
          <caption>
            <b>Table 2.</b> All metrics by language, mean ± SD. English is pooled over every paired English run; the
            ratio row beneath each metric gives the language&apos;s mean ratio to its paired English runs.
          </caption>
          <thead>
            <tr>
              <th>Metric</th>
              <th>English</th>
              {languages.map((l) => (
                <th key={l.finding.target.code}>{l.finding.target.name}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {METRIC_ROWS.map((row) => [
              <tr key={row.key}>
                <th>{row.label}</th>
                <td>
                  <Stat summary={english[row.key]} format={row.format} />
                </td>
                {languages.map((l) => (
                  <td key={l.finding.target.code}>
                    <Stat summary={l.metrics[row.key].target} format={row.format} />
                  </td>
                ))}
              </tr>,
              <tr key={`${row.key}-ratio`} className="ratio-row">
                <th className="sd" style={{ paddingLeft: "1em" }}>× English</th>
                <td className="sd">-</td>
                {languages.map((l) => (
                  <td key={l.finding.target.code} className="sd">
                    {times(l.metrics[row.key].ratio.mean)}
                  </td>
                ))}
              </tr>,
            ])}
          </tbody>
        </table>
      </div>

      <div className="figure-grid">
        {METRIC_ROWS.map((row, i) => (
          <figure key={row.key}>
            <BarFigure
              ariaLabel={`${row.label} by language`}
              format={row.format}
              rows={[
                { label: "English", mean: english[row.key].mean, sd: english[row.key].sd, tone: "english" },
                ...languages.map((l) => ({
                  label: l.finding.target.name,
                  mean: l.metrics[row.key].target.mean,
                  sd: l.metrics[row.key].target.sd,
                  tone: "target",
                  note: times(l.metrics[row.key].ratio.mean),
                })),
              ]}
            />
            <figcaption>
              <b>Figure {i + 2}.</b> {row.label} ({row.hint}; {direction(row)}). Mean ± SD; labels give the ratio to
              paired English runs.
            </figcaption>
          </figure>
        ))}
      </div>

      <AgreementResults analysis={analysis} figureNumber={METRIC_ROWS.length + 2} />
    </>
  );
}

