function paperTitle({ model, languages }) {
  const names = languages.map((l) => l.finding.target.name);
  const compared = names.length <= 3 ? names.join(", ").replace(/, ([^,]*)$/, " and $1") : `${names.length} Languages`;
  return `Cross-Lingual Tokenization Asymmetry in ${model.name}: English vs ${compared}`;
}

/** White-paper layout of the session findings for one model; printed to PDF by the browser. */
export function Paper({ analysis, system, generatedAt }) {
  return (
    <article className="paper">
      <header className="mb-4 text-center">
        <p className="label">Technical report · {generatedAt}</p>
        <h1 contentEditable suppressContentEditableWarning className="mt-2">
          {paperTitle(analysis)}
        </h1>
        <p contentEditable suppressContentEditableWarning className="mt-2 text-[10.5pt]" style={{ textAlign: "center" }}>
          Author Name · Affiliation · email@example.com
        </p>
      </header>

      <Abstract analysis={analysis} />

      <h2>1. Introduction</h2>
      <p>
        Language models price, limit and schedule work in tokens. Because subword tokenizers are trained mostly on
        high-resource languages, the same content can require many more tokens in other languages, raising cost and
        latency and shrinking the usable context {cite("petrov2023")} {cite("ahia2023")}. This report measures that asymmetry
        end to end - from tokenizer fertility to runtime memory and cost - for a single locally hosted model
        {analysis.languages.some((l) => l.finding.target.code === "mi") ? ", with particular attention to Te Reo Māori" : ""}.
      </p>

      <Method analysis={analysis} system={system} />
      <Results analysis={analysis} />

      <h2>4. Limitations</h2>
      <p>
        (i) Queries were machine-translated from English; translation choices change token counts and can shift meaning.
        (ii) Small local models answer poorly in low-resource languages, so answer length and content differ between
        languages; cost per word partly normalises for this. (iii) Timings are wall-clock measurements on one machine with
        both languages running concurrently, and n = {BENCHMARK.repeats} runs per comparison gives only a rough estimate of
        variance. (iv) Text statistics use {TOKENIZER_LABEL}, which differs from the model&apos;s own tokenizer; model token
        counts come from the runtime. (v) Costs are hypothetical, applying hosted-API list prices to a local model.
        (vi) Embedding-based agreement measures topical and semantic closeness, not factual correctness; the multilingual
        encoder is itself less reliable for low-resource languages, which is why a back-translated cross-check is reported.
      </p>

      <h2>References</h2>
      <ol className="refs">
        {REFERENCES.map((ref) => (
          <li key={ref.id}>{ref.text}</li>
        ))}
      </ol>

      <AppendixAnswers analysis={analysis} />
    </article>
  );
}
